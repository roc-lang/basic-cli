#!/usr/bin/env python3
"""Build redistributable MSVC inputs; never copy Microsoft SDK libraries.

Import libraries are generated from Zig's bundled mingw-w64 definitions.
The runtime sources are vendored, with their original license and source hashes.
Both the generated inputs and their notices travel in the platform bundle.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import subprocess
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE_DIR = ROOT / "native" / "windows"
ZIG_VERSION = "0.17.0"
SYSTEM_LIBRARIES = (
    "advapi32", "bcrypt", "crypt32", "dbghelp", "iphlpapi", "kernel32",
    "ncrypt", "ntdll", "ole32", "secur32", "shell32", "user32", "userenv", "ws2_32",
)
UCRT_LIBRARIES = tuple(
    "api-ms-win-crt-" + name + "-l1-1-0"
    for name in (
        "conio", "convert", "environment", "filesystem", "heap", "locale", "math",
        "multibyte", "private", "process", "runtime", "stdio", "string", "time", "utility",
    )
)
IMPORT_LIBRARIES = UCRT_LIBRARIES + SYSTEM_LIBRARIES
RUNTIME_LIBRARIES = ("msvc_runtime.lib",)
LIBRARIES = RUNTIME_LIBRARIES + tuple(name + ".lib" for name in IMPORT_LIBRARIES)
MANIFEST_NAME = "PROVENANCE.json"
PERMISSIVE_LICENSES = {"MIT", "Apache-2.0", "ISC", "BSD-2-Clause", "BSD-3-Clause",
                       "Zlib", "CC0-1.0", "Unlicense", "Unicode-3.0", "UPL-1.0",
                       "CDLA-Permissive-2.0"}


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def command(args: list[str], *, cwd: Path | None = None) -> None:
    subprocess.run(args, cwd=cwd or ROOT, check=True)


def zig_lib_dir() -> Path:
    version = subprocess.check_output(["zig", "version"], text=True).strip()
    if version != ZIG_VERSION:
        raise SystemExit(f"Windows runtime inputs require Zig {ZIG_VERSION}, found {version}")
    # Zig 0.17 prints its environment as ZON, including on Windows.
    output = subprocess.check_output(["zig", "env"], text=True)
    match = re.search(r'\.lib_dir\s*=\s*("(?:[^"\\]|\\.)*")', output)
    if match is None:
        raise SystemExit("zig env did not report lib_dir")
    return Path(json.loads(match[1]))


def source_record(path: Path, root: Path) -> dict[str, str]:
    return {"path": path.relative_to(root).as_posix(), "sha256": digest(path)}


def normalize_definition(source: str) -> str:
    """Win64 has no stdcall @byte-count suffix; leave export ordinals intact."""
    return "; Generated by basic-cli (2026-10-12): x64 stdcall names normalized.\n" + re.sub(
        r"(?<=[A-Za-z0-9_])@\d+\b", "", source
    )


def notice(output: Path, name: str, contents: bytes) -> str:
    path = output / "licenses" / name
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(contents)
    return path.relative_to(output).as_posix()


def build_runtime(output: Path, scratch: Path, zig_lib: Path) -> dict[str, object]:
    upstream = json.loads((SOURCE_DIR / "UPSTREAM.json").read_text())
    for name, expected in upstream["files"].items():
        if digest(SOURCE_DIR / name) != expected:
            raise SystemExit(f"Vendored source changed without updating provenance: {name}")
    license_path = SOURCE_DIR / "LICENSE.roc.txt"
    if digest(license_path) != upstream["license_sha256"]:
        raise SystemExit("Vendored Roc license does not match UPSTREAM.json")
    license_file = notice(output, "roc-UPL-1.0.txt", license_path.read_bytes())
    zig_license = notice(output, "zig-MIT.txt", (zig_lib.parent / "LICENSE").read_bytes())
    basic_cli_license = notice(output, "basic-cli-UPL-1.0.txt",
                               b"Original runtime support: Copyright 2026 basic-cli contributors.\n\n"
                               + (ROOT / "LICENSE").read_bytes())
    common = ["-target", "x86_64-windows-msvc", "-O", "ReleaseFast", "-fno-stack-check"]
    tls = scratch / "tls.obj"
    security = scratch / "security.obj"
    type_info = scratch / "type_info.obj"
    commands = [
        ["zig", "build-obj", str(SOURCE_DIR / "tls.zig"), *common, f"-femit-bin={tls}"],
        ["zig", "build-obj", str(SOURCE_DIR / "security.zig"), *common, f"-femit-bin={security}"],
        ["zig", "c++", "-target", "x86_64-windows-msvc", "-O2", "-g0", "-fno-exceptions",
         "-fno-rtti", "-fno-sized-deallocation",
         "-nostdinc", "-c", str(SOURCE_DIR / "type_info.cpp"), "-o", str(type_info)],
        ["zig", "build-lib", str(SOURCE_DIR / "exe_startup.zig"), str(tls), str(security), str(type_info), *common,
         "-fcompiler-rt", f"-femit-bin={output / 'msvc_runtime.lib'}"],
    ]
    for args in commands:
        command(args)
    return {
        "component": "Roc MSVC startup, initializer tables, TLS, and Zig compiler-rt",
        "source_url": "https://github.com/roc-lang/roc/tree/" + upstream["commit"]
                      + "/src/default_platform/msvc_runtime",
        "source_revision": upstream["commit"],
        "sources": [source_record(SOURCE_DIR / name, SOURCE_DIR) for name in upstream["files"]],
        "zig_version": ZIG_VERSION,
        "compiler_rt_sources": [source_record(p, zig_lib) for p in sorted(
            [zig_lib / "compiler_rt.zig", *(zig_lib / "compiler_rt").rglob("*.zig")])],
        "license": "UPL-1.0 AND MIT",
        "license_files": [license_file, zig_license, basic_cli_license],
        "redistribution_basis": "UPL-1.0 and MIT permit source and binary redistribution with notices retained.",
        "build_commands": commands,
        "local_sources": [source_record(SOURCE_DIR / name, ROOT) for name in ("security.zig", "type_info.cpp")],
        "modifications": ["Added original UPL-1.0 stack-cookie and MSVC type-info metadata support; upstream Roc sources are unmodified."],
    }


def build_imports(output: Path, scratch: Path, zig_lib: Path) -> dict[str, object]:
    mingw = zig_lib / "libc" / "mingw"
    license_file = notice(output, "mingw-w64-ZPL-2.1.txt", (mingw / "COPYING").read_bytes())
    # Record the complete input definition/include set, not only the entry .def.
    sources = [source_record(p, zig_lib) for directory in ("lib-common", "lib64", "def-include")
               for p in sorted((mingw / directory).rglob("*")) if p.is_file()]
    commands: list[list[str]] = []
    for name in IMPORT_LIBRARIES:
        candidates = [mingw / directory / (name + suffix)
                      for directory in ("lib64", "lib-common") for suffix in (".def", ".def.in")]
        source = next((p for p in candidates if p.is_file()), None)
        if source is None:
            raise SystemExit(f"Zig {ZIG_VERSION} has no mingw-w64 definition for {name}")
        definition = scratch / (name + ".def")
        args = ["zig", "cc", "-E", "-P", "-x", "c", "-target", "x86_64-windows-msvc",
                "-Wno-extra-tokens", "-Wno-invalid-pp-token",
                "-I", str(mingw / "def-include"), "-I", str(mingw / "lib-common"),
                str(source), "-o", str(definition)]
        command(args)
        commands.append(args)
        definition.write_text(normalize_definition(definition.read_text()), encoding="utf-8")
        args = ["zig", "dlltool", "-m", "i386:x86-64", "-d", str(definition),
                "-l", str(output / (name + ".lib"))]
        command(args)
        commands.append(args)
    return {
        "component": "mingw-w64 UCRT and Win32 import definitions bundled with Zig",
        "source_url": f"https://ziglang.org/download/{ZIG_VERSION}/zig-{ZIG_VERSION}.tar.xz",
        "source_sha256": "b6c7f1728f043700d6529bac980800792f824256a9d2f1839b3d62beed0b8abd",
        "zig_version": ZIG_VERSION,
        "sources": sources,
        "license": "ZPL-2.1",
        "license_files": [license_file],
        "redistribution_basis": "mingw-w64 COPYING permits source and binary redistribution with its copyright, conditions, and disclaimer retained.",
        "build_commands": commands,
        "modifications": ["Preprocessed architecture-specific definitions and removed stdcall @byte-count suffixes for x64 COFF imports (2026-10-12); source files are unmodified and no DLL code is distributed."],
    }


def validate(output: Path, *, require_host: bool = True) -> list[Path]:
    manifest_path = output / MANIFEST_NAME
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    if manifest.get("format_version") != 1:
        raise ValueError("Unsupported Windows provenance format")
    records = manifest.get("libraries", {})
    expected = set(LIBRARIES) | ({"host.lib"} if require_host else set())
    inventory = {p.name for p in output.glob("*.lib") if p.is_file()
                 and (require_host or p.name != "host.lib")}
    actual = {p.name for p in output.glob("*.lib") if p.stat().st_size
              and (require_host or p.name != "host.lib")}
    if inventory != expected or actual != expected or set(records) != expected:
        raise ValueError(f"Windows library inventory mismatch: expected={sorted(expected)}, actual={sorted(actual)}")
    documents = {manifest_path}
    for name, record in records.items():
        if record.get("sha256") != digest(output / name):
            raise ValueError(f"Windows library hash mismatch: {name}")
        component = manifest["components"][record["component"]]
        for key in ("license", "license_files", "redistribution_basis", "sources", "build_commands"):
            if not component.get(key):
                raise ValueError(f"Missing {key} for Windows component {record['component']}")
        for relative in component["license_files"]:
            path = output / relative
            if not path.resolve().is_relative_to(output.resolve()) or not path.is_file() or not path.stat().st_size:
                raise ValueError(f"Missing or invalid Windows license file: {relative}")
            if manifest["documents"].get(relative) != digest(path):
                raise ValueError(f"Windows license hash mismatch: {relative}")
            documents.add(path)
    return sorted(documents)


def write_manifest(output: Path, components: dict[str, object], library_components: dict[str, str]) -> None:
    documents = {relative for component in components.values() for relative in component["license_files"]}
    manifest = {
        "format_version": 1,
        "components": components,
        "libraries": {name: {"component": component, "sha256": digest(output / name)}
                      for name, component in library_components.items()},
        "documents": {relative: digest(output / relative) for relative in sorted(documents)},
    }
    (output / MANIFEST_NAME).write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")


def record_host(output: Path, build_commands: list[list[str]], toolchain: dict[str, str]) -> None:
    """Collect actual Cargo source-package licenses, including component notices.

    SPDX metadata is a check against the reviewed permissive set, not a grant of
    rights by itself. The original license/notice files and source checksums are
    recorded together, and components without notices stop the build.
    """
    metadata = json.loads(subprocess.check_output([
        "cargo", "metadata", "--locked", "--format-version=1", "--filter-platform",
        "x86_64-pc-windows-msvc"], cwd=ROOT, text=True))
    nodes = {n["id"]: n for n in metadata["resolve"]["nodes"]}
    wanted: set[str] = set()
    pending = [metadata["resolve"]["root"]]
    while pending:
        node_id = pending.pop()
        if node_id in wanted:
            continue
        wanted.add(node_id)
        pending.extend(d["pkg"] for d in nodes[node_id]["deps"]
                       if any(k["kind"] is None for k in d["dep_kinds"]))
    checksums = {(p["name"], p["version"]): p.get("checksum")
                 for p in tomllib.loads((ROOT / "Cargo.lock").read_text())["package"]}
    packages: list[dict[str, object]] = []
    license_files: set[str] = set()
    for package in sorted(metadata["packages"], key=lambda p: (p["name"], p["version"])):
        if package["id"] not in wanted:
            continue
        expression = package["license"]
        if not expression or set(re.findall(r"[A-Za-z0-9.-]+", expression)) - PERMISSIVE_LICENSES - {"AND", "OR"}:
            raise SystemExit(f"Unreviewed license expression: {package['name']} {expression!r}")
        directory = Path(package["manifest_path"]).parent
        if package["source"] is None:
            originals = [ROOT / "LICENSE"]
        else:
            originals = sorted(p for p in directory.rglob("*") if p.is_file()
                               and re.match(r"^(LICENSE|COPYING|NOTICE|UNLICENSE)([._-]|$)", p.name, re.I))
        if not originals:
            raise SystemExit(f"No license files for {package['name']} {package['version']}")
        package_licenses = []
        for original in originals:
            relative = original.relative_to(directory).as_posix()
            copied = notice(output, f"cargo/{package['name']}-{package['version']}/{relative}", original.read_bytes())
            package_licenses.append(copied)
            license_files.add(copied)
        # Source file copyright headers can carry notices beyond the package's
        # common license text (ring's BoringSSL assembly is one such component).
        copyrights = []
        if package["source"] is not None:
            for original in sorted(directory.rglob("*")):
                if original.is_file() and original.suffix in {".rs", ".c", ".cc", ".h", ".S", ".asm"}:
                    header = original.read_text(encoding="utf-8", errors="replace").splitlines()[:100]
                    if any("copyright" in line.lower() or "public domain" in line.lower() for line in header):
                        copyrights.append(original.relative_to(directory).as_posix() + "\n" + "\n".join(header))
            if copyrights:
                copied = notice(output, f"cargo/{package['name']}-{package['version']}/SOURCE-NOTICES.txt",
                                ("\n\n".join(copyrights) + "\n").encode())
                package_licenses.append(copied)
                license_files.add(copied)
        packages.append({
            "name": package["name"], "version": package["version"], "license": expression,
            "source": package["source"], "repository": package["repository"],
            "source_package_sha256": checksums[(package["name"], package["version"])],
            "license_files": package_licenses,
        })
    # This Rust-supplied document includes full notices for the standard library
    # and its compiler-builtins/native components, not just Cargo dependencies.
    sysroot = Path(subprocess.check_output(["rustc", "--print", "sysroot"], text=True).strip())
    rust_notices = sysroot / "share" / "doc" / "rust" / "COPYRIGHT-library.html"
    if not rust_notices.is_file():
        raise SystemExit("Rust standard library notices are missing; install the rust-docs component")
    license_files.add(notice(output, "rust/COPYRIGHT-library.html", rust_notices.read_bytes()))
    sources = [source_record(p, ROOT) for p in sorted((ROOT / "src").rglob("*.rs"))]
    sources.extend(source_record(ROOT / name, ROOT) for name in ("Cargo.toml", "Cargo.lock", "rust-toolchain.toml"))
    manifest = json.loads((output / MANIFEST_NAME).read_text())
    manifest["components"]["host"] = {
        "component": "basic-cli Rust MSVC static host and its embedded dependencies",
        "source_url": "https://github.com/roc-lang/basic-cli",
        "source_revision": subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=ROOT, text=True).strip(),
        "sources": sources,
        "license": "UPL-1.0 and the individual Cargo/Rust component licenses",
        "license_files": sorted(license_files),
        "redistribution_basis": "Original permissive source-package licenses and Rust's component copyright/license document are included; no Microsoft CRT/SDK archives are incorporated.",
        "build_commands": build_commands,
        "modifications": [],
        "toolchain": toolchain,
        "rust_version": subprocess.check_output(["rustc", "-vV"], text=True).strip(),
        "packages": packages,
    }
    mapping = {name: value["component"] for name, value in manifest["libraries"].items()}
    mapping["host.lib"] = "host"
    write_manifest(output, manifest["components"], mapping)
    validate(output)


def build(output: Path) -> None:
    output = output.resolve()
    output.mkdir(parents=True, exist_ok=True)
    scratch = ROOT / "target" / "windows-runtime"
    scratch.mkdir(parents=True, exist_ok=True)
    zig_lib = zig_lib_dir()
    components = {"runtime": build_runtime(output, scratch, zig_lib),
                  "imports": build_imports(output, scratch, zig_lib)}
    write_manifest(output, components, {name: "runtime" if name in RUNTIME_LIBRARIES else "imports"
                                       for name in LIBRARIES})
    validate(output, require_host=False)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path, default=ROOT / "platform" / "targets" / "x64win")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.check:
        validate(args.output_dir)
    else:
        build(args.output_dir)


if __name__ == "__main__":
    main()
