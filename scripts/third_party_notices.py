#!/usr/bin/env python3
"""Generate the third-party notices for everything linked into the platform hosts.

The hand-written preamble of THIRD_PARTY_LICENSES.md is kept. Everything after
its marker is regenerated from `cargo metadata` for every Roc target, each
linked package's original license files and source copyright lines, and the
prebuilt native inputs recorded in licenses/native-inputs.json.

Run without arguments after changing Cargo.lock, the Rust toolchain or a
prebuilt native input. `--check` fails when the committed notices are stale.
"""
from __future__ import annotations

import argparse
import difflib
import itertools
import json
import re
import subprocess
from collections.abc import Iterable, Iterator
from pathlib import Path

try:
    from . import build, windows_runtime
except ImportError:
    import build
    import windows_runtime


ROOT = Path(__file__).resolve().parents[1]
NOTICES = ROOT / "THIRD_PARTY_LICENSES.md"
LICENSES_DIR = ROOT / "licenses"
NATIVE_INPUTS = LICENSES_DIR / "native-inputs.json"
MARKER = "<!-- Everything below is generated by scripts/third_party_notices.py. Do not edit it by hand. -->"
RUST_TARGETS = {**build.TARGETS, "x64win": build.WINDOWS_TARGET}
# Built from Cargo sources, so covered by the Cargo section.
GENERATED_INPUTS = {"libhost.a"}
LICENSE_FILE = re.compile(r"^(LICEN[CS]E|COPYING|COPYRIGHT|NOTICE|UNLICENSE)([._-]|$)", re.I)
SOURCE_SUFFIXES = {".rs", ".c", ".cc", ".cpp", ".h", ".hpp", ".inl", ".S", ".asm", ".pl"}
# Never license texts, even when named like one (e.g. `src/license.rs`).
CODE_SUFFIXES = {".py", ".sh", ".toml", ".json", ".yml", ".yaml"}
HEADER_LINES = 100
# Comment leaders of the scanned languages, including assembler `@` and `;`.
# `#` excludes shebangs, Rust attributes and C preprocessor directives.
COMMENT = re.compile(r"^\s*(//+!?|/\*+!?|\*+/?|@|;+|#+(?!\s*(?:!|\[|(?:if|ifdef|ifndef|elif|else|endif"
                     r"|define|undef|include|pragma|error)\b)))")
LICENSE_EXCEPTIONS = {"LLVM-exception"}


class NoticeError(Exception):
    pass


def linked_packages(metadata: dict) -> list[dict]:
    """Packages reachable from the root through normal (not build or dev) dependencies."""
    nodes = {node["id"]: node for node in metadata["resolve"]["nodes"]}
    root = metadata["resolve"]["root"]
    linked: set[str] = set()
    pending = [root]
    while pending:
        node_id = pending.pop()
        if node_id in linked:
            continue
        linked.add(node_id)
        pending.extend(dep["pkg"] for dep in nodes[node_id]["deps"]
                       if any(kind["kind"] is None for kind in dep["dep_kinds"]))
    return [p for p in metadata["packages"] if p["id"] in linked and p["id"] != root]


def check_license(package: dict) -> None:
    expression = package.get("license") or ""
    names = set(re.findall(r"[A-Za-z0-9.+-]+", expression)) - {"AND", "OR", "WITH"}
    unreviewed = names - windows_runtime.PERMISSIVE_LICENSES - LICENSE_EXCEPTIONS
    if not names or unreviewed:
        raise NoticeError(f"Unreviewed license expression for {package['name']} "
                          f"{package['version']}: {expression!r}")


def normalize(text: str) -> str:
    lines = text.replace("\r\n", "\n").replace("\r", "\n").split("\n")
    return "\n".join(line.rstrip() for line in lines).strip("\n")


def license_texts(package: dict) -> list[tuple[str, str]]:
    directory = Path(package["manifest_path"]).parent
    paths = {p for p in directory.rglob("*") if p.is_file() and LICENSE_FILE.match(p.name)
             and p.suffix not in SOURCE_SUFFIXES | CODE_SUFFIXES}
    if package.get("license_file"):
        paths.add(directory / package["license_file"])
    texts = [(p.relative_to(directory).as_posix(), normalize(p.read_text(encoding="utf-8", errors="replace")))
             for p in paths]
    texts = sorted((name, text) for name, text in texts if text)
    if not texts:
        raise NoticeError(f"No license files for {package['name']} {package['version']}")
    return texts


def header_paragraphs(lines: Iterable[str]) -> Iterator[str]:
    """Comment paragraphs, without comment markers, from the start of a source file."""
    paragraph: list[str] = []
    for line in lines:
        comment = COMMENT.match(line)
        text = re.sub(r"\*+/\s*$", "", line[comment.end():]).strip() if comment else ""
        if text:
            paragraph.append(text)
        elif paragraph:
            yield "\n".join(paragraph)
            paragraph = []
    if paragraph:
        yield "\n".join(paragraph)


def source_copyrights(package: dict) -> list[str]:
    """Copyright statements in source headers, which may name holders the license files omit."""
    directory = Path(package["manifest_path"]).parent
    found = set()
    for path in directory.rglob("*"):
        if not path.is_file() or path.suffix not in SOURCE_SUFFIXES:
            continue
        with path.open(encoding="utf-8", errors="replace") as source:
            for paragraph in header_paragraphs(itertools.islice(source, HEADER_LINES)):
                lowered = paragraph.lower()
                if "copyright" in lowered or "public domain" in lowered:
                    found.add(paragraph)
    return sorted(found)


def cargo_packages(rust_targets: dict[str, str]) -> list[dict]:
    """Every linked package across targets, with the Roc targets that link it."""
    packages: dict[str, dict] = {}
    for roc_target, rust_target in rust_targets.items():
        metadata = json.loads(subprocess.check_output(
            ["cargo", "metadata", "--locked", "--format-version=1", "--filter-platform", rust_target],
            cwd=ROOT, text=True))
        for package in linked_packages(metadata):
            entry = packages.setdefault(package["id"], {**package, "roc_targets": []})
            entry["roc_targets"].append(roc_target)
    result = sorted(packages.values(), key=lambda p: (p["name"], p["version"]))
    for package in result:
        if package["source"] is None:
            raise NoticeError(f"Local path dependency {package['name']} needs a reviewed notice")
        check_license(package)
    return result


def native_components(root: Path = ROOT) -> list[dict]:
    """Recorded prebuilt inputs, after checking that they match the files we ship."""
    components = json.loads((root / "licenses" / "native-inputs.json").read_text(encoding="utf-8"))["components"]
    recorded: set[str] = set()
    for component in components:
        if not (root / "licenses" / component["license_file"]).is_file():
            raise NoticeError(f"Missing license file for {component['name']}: {component['license_file']}")
        for relative, expected in component["files"].items():
            path = root / relative
            if not path.is_file() or windows_runtime.digest(path) != expected:
                raise NoticeError(f"{relative} does not match licenses/native-inputs.json; "
                                  "record the new input's origin, hash and license")
            recorded.add(relative)
    for target in build.TARGETS:
        directory = root / "platform" / "targets" / target
        shipped = {p.relative_to(root).as_posix() for p in directory.rglob("*")
                   if p.is_file() and p.name not in GENERATED_INPUTS} if directory.is_dir() else set()
        if shipped - recorded:
            raise NoticeError(f"Prebuilt inputs without a provenance record: {sorted(shipped - recorded)}")
    return components


def rust_version(root: Path = ROOT) -> str:
    match = re.search(r'^channel\s*=\s*"([^"]+)"', (root / "rust-toolchain.toml").read_text(), re.MULTILINE)
    if match is None:
        raise NoticeError("rust-toolchain.toml has no channel")
    return match[1]


def code_block(text: str) -> str:
    fence = "`" * max(3, 1 + max((len(run) for run in re.findall(r"`+", text)), default=0))
    return f"{fence}text\n{text}\n{fence}\n"


def target_list(targets: list[str]) -> str:
    return "all" if set(targets) == set(RUST_TARGETS) else ", ".join(targets)


def render(packages: list[dict], components: list[dict], rust: str, licenses_dir: Path = LICENSES_DIR) -> str:
    out = [MARKER, ""]
    out += [
        "## Prebuilt native inputs",
        "",
        "These Linux musl inputs are committed as binaries. Their hashes are checked",
        "against `licenses/native-inputs.json`, which records where each one came from.",
        "",
        "| File | Component | SHA-256 |",
        "| --- | --- | --- |",
    ]
    for component in components:
        for relative, sha256 in sorted(component["files"].items()):
            out.append(f"| `{relative}` | {component['name']} {component['version']} | `{sha256}` |")
    out.append("")
    texts: dict[str, list[dict]] = {}
    for component in components:
        texts.setdefault(component["license_file"], []).append(component)
    for license_file, users in texts.items():
        out += [f"### {users[0]['name']}", ""]
        for component in users:
            out += [f"- {component['version']} ({component['license']}): {component['origin']}.",
                    f"  License: {component['upstream']}"]
        out += ["", code_block(normalize((licenses_dir / license_file).read_text(encoding="utf-8")))]

    out += [
        "## Rust standard library",
        "",
        f"Every host statically links the Rust {rust} standard library. Its notices,",
        "including those for its own dependencies, are in Rust's `COPYRIGHT-library.html`,",
        "which release bundles carry as `targets/x64win/licenses/rust/COPYRIGHT-library.html`.",
        "The document covers the standard library for all targets.",
        "",
        "## Cargo packages",
        "",
        "Generated from `Cargo.lock` for every Roc target. This lists normal dependencies",
        "(including procedural macros) but not build or dev dependencies, which are not",
        "linked into a host. Every license file in a package's source is reproduced, so",
        "for dual-licensed packages each offered license is included.",
        "",
        "| Package | Version | License | Targets |",
        "| --- | --- | --- | --- |",
    ]
    groups: dict[str, list[str]] = {}
    representative: dict[str, str] = {}
    for package in packages:
        out.append(f"| {package['name']} | {package['version']} | {package['license']} "
                   f"| {target_list(package['roc_targets'])} |")
        for name, text in license_texts(package):
            key = " ".join(text.split())
            groups.setdefault(key, []).append(f"{package['name']} {package['version']} (`{name}`)")
            representative.setdefault(key, text)
    out += ["", "### License texts", ""]
    for key, users in sorted(groups.items(), key=lambda item: item[1]):
        out += ["Applies to: " + ", ".join(users) + ".", "", code_block(representative[key])]

    out += ["### Source copyright notices", "",
            "Copyright statements found in the headers of each package's source files.", ""]
    for package in packages:
        statements = source_copyrights(package)
        if statements:
            out += [f"#### {package['name']} {package['version']}", "", code_block("\n".join(statements))]
    return "\n".join(out).rstrip("\n") + "\n"


def expected_notices(current: str) -> str:
    preamble, marker, _ = current.partition(MARKER)
    if not marker:
        raise NoticeError(f"{NOTICES.name} is missing the generated-section marker")
    return preamble + render(cargo_packages(RUST_TARGETS), native_components(), rust_version())


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if THIRD_PARTY_LICENSES.md is stale")
    args = parser.parse_args()
    current = NOTICES.read_text(encoding="utf-8")
    try:
        expected = expected_notices(current)
    except NoticeError as error:
        raise SystemExit(f"error: {error}") from None
    if not args.check:
        NOTICES.write_text(expected, encoding="utf-8", newline="\n")
        return
    if current != expected:
        diff = difflib.unified_diff(current.splitlines(), expected.splitlines(),
                                    "committed", "generated", lineterm="", n=1)
        print("\n".join(itertools.islice(diff, 60)))
        raise SystemExit(f"error: {NOTICES.name} is stale; run `python3 scripts/third_party_notices.py`")


if __name__ == "__main__":
    try:
        main()
    except subprocess.CalledProcessError as error:
        raise SystemExit(error.returncode) from None
